    private static void createSchema(JdbcTemplate jdbc) {
        jdbc.execute("CREATE TABLE workitem (id BIGINT PRIMARY KEY, tenant_id BIGINT, title VARCHAR(200), "
                + "template_id BIGINT, status_node_id BIGINT, assignee_type VARCHAR(20), assignee_ref BIGINT, "
                + "priority INT DEFAULT 2, gmt_create TIMESTAMP, gmt_modified TIMESTAMP, is_deleted INT DEFAULT 0)");
        jdbc.execute("CREATE TABLE status_node (id BIGINT PRIMARY KEY, tenant_id BIGINT, template_id BIGINT, "
                + "code VARCHAR(64), name VARCHAR(100), category VARCHAR(20))");
        jdbc.execute("CREATE TABLE dispatch (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id BIGINT, workitem_id BIGINT, source_type VARCHAR(32), "
                + "status VARCHAR(20), is_deleted INT DEFAULT 0, attempt INT DEFAULT 0, resume_mode VARCHAR(32), "
                + "idempotency_key VARCHAR(128), error VARCHAR(512), agent_id BIGINT, executor_id BIGINT, "
                + "gmt_create TIMESTAMP, gmt_modified TIMESTAMP)");
        jdbc.execute("CREATE TABLE dispatch_request (dispatch_id BIGINT, tenant_id BIGINT, kind VARCHAR(20), "
                + "status VARCHAR(20), expires_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE workitem_event (id BIGINT PRIMARY KEY, tenant_id BIGINT, workitem_id BIGINT, "
                + "event_type VARCHAR(32), to_val VARCHAR(64), gmt_create TIMESTAMP)");
        jdbc.execute("CREATE TABLE dispatch_ai_usage (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "tenant_id BIGINT, usage_at TIMESTAMP, total_tokens BIGINT)");
        jdbc.execute("CREATE TABLE dispatch_result_decision (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "tenant_id BIGINT, dispatch_id BIGINT, failure_category VARCHAR(128), decided_at TIMESTAMP)");
    }

    private static org.apache.ibatis.session.SqlSessionFactory factory(DriverManagerDataSource ds) throws Exception {
        var configuration = new Configuration(new Environment("test", new JdbcTransactionFactory(), ds));
        configuration.setDatabaseId("ainative-source-aware");
        for (String name : List.of("WorkitemDao", "DeliveryOverviewDao")) {
            try (var stream = Files.newInputStream(Path.of("src/main/resources/mapping/" + name + ".xml"))) {
                new XMLMapperBuilder(stream, configuration, name, configuration.getSqlFragments()).parse();
            }
        }
        return new SqlSessionFactoryBuilder().build(configuration);
    }

